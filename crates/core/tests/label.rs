use statsbar_core::label::rate_text;

#[test]
fn rate_text_bands_like_the_menu_bar_rate() {
    for (rate, text) in [
        (0.0, "0B"),
        (999.4, "999B"),
        (999.5, "1K"),
        (12_000.0, "12K"),
        (999_499.0, "999K"),
        (999_500.0, "1.0M"),
        (9_949_999.0, "9.9M"),
        (9_950_000.0, "10M"),
        (999_499_999.0, "999M"),
        (999_500_000.0, "1.0G"),
        (12_000_000_000.0, "12G"),
        (999_499_999_999.0, "999G"),
        (1e15, "999G"),
        (f64::INFINITY, "999G"),
        (f64::NAN, "0B"),
        (-5.0, "0B"),
        (-0.0, "0B"),
    ] {
        assert_eq!(rate_text(rate), text, "{rate}");
    }
}
